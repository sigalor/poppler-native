#!/usr/bin/env node
// Regenerates native/binding/text-repair/reference-fingerprints.inc: the glyph-outline fingerprints the text repair
// uses to read text drawn with an embedded subset of a known font that has no usable ToUnicode map.
//
//   node scripts/generate-reference-fingerprints.mjs Arial=<path to Arial.ttf> Arial-Bold=<path to Arial Bold.ttf>
//
// The fonts themselves are not part of poppler-native; only these fingerprints are. The addon must be built first:
// the fingerprints come from its own _referenceFingerprints(), the same code that fingerprints embedded glyphs.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'native', 'binding', 'text-repair', 'reference-fingerprints.inc');

function fail(message) {
  console.error(`generate-reference-fingerprints: ${message}`);
  process.exit(1);
}

const fonts = process.argv.slice(2).map(arg => {
  const match = arg.match(/^([A-Za-z][A-Za-z0-9-]*)=(.+)$/);
  if (!match) fail('usage: node scripts/generate-reference-fingerprints.mjs <PDF font name>=<file.ttf> ...');
  return { name: match[1], file: match[2] };
});
if (fonts.length === 0) fail('no fonts given');

const native = require('../lib/native');
const identifier = name => `k${name.replace(/[^A-Za-z0-9]/g, '')}`;
const hexList = (values, format, perLine) =>
  values
    .map(format)
    .reduce((lines, value, i) => {
      if (i % perLine === 0) lines.push([]);
      lines[lines.length - 1].push(value);
      return lines;
    }, [])
    .map(line => `    ${line.join(', ')},`)
    .join('\n');

let out =
  '// Generated by scripts/generate-reference-fingerprints.mjs. Do not edit.\n' +
  '// Per reference font: outline fingerprints in ascending order, for each the start of its codepoints in the\n' +
  '// codepoint list (plus a final end offset), and the codepoints, canonical first (see GlyphFingerprint.hpp).\n\n';
const registry = [];
for (const { name, file } of fonts) {
  const entries = native._referenceFingerprints(fs.readFileSync(file));
  entries.sort(([a], [b]) => (BigInt(`0x${a}`) < BigInt(`0x${b}`) ? -1 : 1));
  const offsets = [];
  const codepoints = [];
  for (const [, cps] of entries) {
    offsets.push(codepoints.length);
    codepoints.push(...cps);
  }
  offsets.push(codepoints.length);
  const id = identifier(name);
  out += `// ${name}: ${entries.length} outlines, ${codepoints.length} codepoints (from ${path.basename(file)})\n`;
  out += `static const uint64_t ${id}Fingerprints[] = {\n${hexList(entries.map(([fp]) => fp), fp => `0x${fp}ULL`, 4)}\n};\n`;
  out += `static const uint32_t ${id}Offsets[] = {\n${hexList(offsets, n => String(n), 12)}\n};\n`;
  out += `static const uint32_t ${id}Codepoints[] = {\n${hexList(codepoints, cp => `0x${cp.toString(16)}`, 12)}\n};\n\n`;
  registry.push(`    {"${name}", ${id}Fingerprints, ${id}Offsets, ${id}Codepoints, ${entries.length}},`);
}
out += `static const ReferenceFontData kReferenceFontData[] = {\n${registry.join('\n')}\n};\n`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} (${fonts.map(f => f.name).join(', ')})`);
