async function obtain(library, spec, dir, work) {
  const name = path.basename(new URL(spec.url).pathname);
  const archive = path.join(work, `${library}-${name}`);
  const local = dir && path.join(dir, name);
  if (local && fs.existsSync(local)) {
    fs.copyFileSync(local, archive);
    if (spec.signature) fs.copyFileSync(local + spec.signature.suffix, archive + spec.signature.suffix);
  } else {
    await download(spec.url, archive);
    if (spec.signature) await download(spec.url + spec.signature.suffix, archive + spec.signature.suffix);
  }
  const actual = sha256(archive);
  if (actual !== spec.sha256) throw new Error(`${library}: sha256 ${actual} does not match the pinned ${spec.sha256}`);
  if (spec.signature) {
    verifySignature(archive, archive + spec.signature.suffix, path.join(KEYS, spec.signature.key), spec.signature.fingerprint);
  }
  return archive;
}

async function vendor(library, dir) {
  const spec = LIBRARIES[library];
  const work = fs.mkdtempSync(path.join(os.tmpdir(), `poppler-native-${library}-`));
  try {
    const archive = await obtain(library, spec, dir, work);
    extract(archive, path.join(work, 'src'));
    const tarballRoot = path.join(work, 'src', spec.tarballRoot);
    const srcRoot = path.join(tarballRoot, spec.sourceRoot || '.');

    const sources = spec.sources(srcRoot);
    for (const source of sources) {
      if (!fs.existsSync(path.join(srcRoot, source))) throw new Error(`${library}: ${source} does not exist`);
    }
    const files = new Set(includeClosure(srcRoot, sources, { dirs: ['.'], includePaths: ['.', ...(spec.includePaths || [])] }));
    for (const copyDir of spec.copyDirs || []) {
      for (const file of listFiles(path.join(srcRoot, copyDir))) {
        if (/\.(c|h)$/.test(file)) files.add(`${copyDir}/${file}`);
      }
    }

    const dest = path.join(DEPS, library);
    fs.rmSync(dest, { recursive: true, force: true });
    fs.rmSync(path.join(DEPS, 'config', library), { recursive: true, force: true });
    for (const file of files) {
      fs.mkdirSync(path.join(dest, path.dirname(file)), { recursive: true });
      fs.copyFileSync(path.join(srcRoot, file), path.join(dest, file));
    }
    for (const license of spec.licenses) {
      fs.copyFileSync(path.join(tarballRoot, license), path.join(dest, path.basename(license)));
    }
    if (spec.configure) spec.configure(tarballRoot, spec.version);
    fs.writeFileSync(
      path.join(DEPS, `${library}.sources.gypi`),
      sourcesGypi(`Generated by scripts/vendor-deps.mjs for ${library} ${spec.version}`, sources.map(s => `${library}/${s}`)),
    );
    console.log(`${library} ${spec.version}: ${sources.length} sources, ${files.size} files`);
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

async function main() {
  const args = process.argv.slice(2);
  const dirIndex = args.indexOf('--dir');
  const dir = dirIndex >= 0 ? path.resolve(args.splice(dirIndex, 2)[1]) : null;
  const libraries = args.length ? args : Object.keys(LIBRARIES);
  for (const library of libraries) {
    if (!LIBRARIES[library]) fail(`unknown library ${library}; one of ${Object.keys(LIBRARIES).join(', ')}`);
    try {
      await vendor(library, dir);
    } catch (e) {
      if (e instanceof Failure) throw e;
      fail(e.message);
    }
  }
  fs.writeFileSync(
    path.join(DEPS, 'versions.json'),
    `${JSON.stringify(Object.fromEntries(Object.entries(LIBRARIES).map(([name, s]) => [name, { version: s.version, url: s.url, sha256: s.sha256 }])), null, 2)}\n`,
  );
}

await runScript(main);
