#!/usr/bin/env node
// Vendors the C libraries poppler-native compiles into the addon, so that building from source needs nothing but a
// C/C++ compiler -- no system libraries or headers -- and every prebuilt binary is self-contained.
//
//   node scripts/vendor-deps.mjs [<library> ...] [--dir <directory with already downloaded releases>]
//
// For each library (default: all of them) it takes the release pinned in LIBRARIES, checks its sha256 and, where
// upstream signs releases, the signature against the key committed in scripts/keys/; then replaces
// native/deps/<library>/ with exactly the sources the build compiles plus every file they #include, writes
// native/deps/<library>.sources.gypi, and renders the library's configuration headers from upstream's templates
// into native/deps/config/<library>/. To move to a new release, change version, url and sha256 below and re-run:
// a template that grew a new option makes the run fail until that option is decided here.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  Failure,
  download,
  extract,
  fail as failWith,
  includeClosure,
  listFiles,
  renderCMakeTemplate,
  runScript,
  sha256,
  sourcesGypi,
  verifySignature,
} from './lib/vendoring.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const DEPS = path.join(ROOT, 'native', 'deps');
const KEYS = path.join(ROOT, 'scripts', 'keys');
const fail = message => failWith('vendor-deps', message);

// The `set(<name> ...)` list of a CMakeLists.txt, as whitespace-separated entries.
function cmakeList(cmakeFile, name) {
  const text = fs.readFileSync(cmakeFile, 'utf8');
  const match = text.match(new RegExp(`^set\\(${name}\\s([\\s\\S]*?)\\)`, 'm'));
  if (!match) throw new Error(`no set(${name} ...) in ${cmakeFile}`);
  return match[1].split(/\s+/).filter(Boolean);
}

function cmakeVariable(cmakeFile, name) {
  const match = fs.readFileSync(cmakeFile, 'utf8').match(new RegExp(`^set\\(${name}\\s+"?([^")]+)"?\\)`, 'm'));
  if (!match) throw new Error(`no set(${name} ...) in ${cmakeFile}`);
  return match[1].trim();
}

function writeConfig(library, file, text) {
  const out = path.join(DEPS, 'config', library, file);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
}

const banner = (library, version, template) =>
  `/* Generated by scripts/vendor-deps.mjs from ${library} ${version}'s ${template}. Do not edit. */\n`;

function render(library, version, srcRoot, template, flags, values, prelude = '') {
  const { text } = renderCMakeTemplate(fs.readFileSync(path.join(srcRoot, template), 'utf8'), {
    flags,
    values,
    name: `${library} ${template}`,
  });
  return banner(library, version, template) + prelude + text;
}

